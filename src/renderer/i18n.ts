export const TRANSLATION_KEYS = [...new Set([...Object.values(EN), ...Object.keys(EXTRA_ZH)])];
const STRINGS = Object.fromEntries(LANGUAGE_CODES.map(language => [language,
  language === 'en' ? EN : language === 'zh-CN' ? ZH : Object.fromEntries(Object.entries(EN).map(([key, value]) => [key, LOCALES[language]?.[value] ?? value]))
])) as Record<UiLanguage, UiStrings>;
const CHINESE_TEXT: Record<string, string> = {
  ...Object.fromEntries(Object.keys(EN).map(key => [EN[key as keyof typeof EN], ZH[key as keyof typeof EN]])),
  ...EXTRA_ZH,
  ...STATIC_ZH
};

export function translate(english: string, vars: Record<string, string | number> = {}): string {
  const template = current === 'zh-CN' ? CHINESE_TEXT[english] ?? english : LOCALES[current]?.[english] ?? english;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key: string) => String(vars[key] ?? match));
}

let current: UiLanguage = 'en';

export function uiLanguage(): UiLanguage {
  return current;
}

export function setUiLanguage(language: UiLanguage): UiLanguage {
  current = LANGUAGE_CODES.includes(language) ? language : 'en';
  // Persisted config.ui.language is the sole authority; no competing browser cache.
  if (typeof document !== 'undefined') document.documentElement.lang = current;
  return current;
}

export function ui(): UiStrings {
  return STRINGS[current];
}

export function t(key: string, vars: Record<string, string | number> = {}): string {
  const table = STRINGS[current] as Record<string, string>;
  const template = table[key] ?? EN[key as keyof typeof EN] ?? key;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_match: string, name: string) => {
    const value = vars[name];
    return value === undefined || value === null ? '' : String(value);
  });
}
